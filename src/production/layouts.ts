export const nativeLifeId=(n:number)=>'life-'+String(n).padStart(3,'0');
export function layoutDependencies(n:number){const layout=lifeLayouts[n];if(!layout)throw new Error('未知生活组合配方');return [...new Set(layout.map(v=>typeof v[0]==='string'?v[0]:nativeLifeId(v[0])))];}
export function makeLifeAssembly(project:Project,catalogId:string,id:string,name:string):Assembly{
 const layout=lifeLayouts[Number(catalogId.slice(5))];if(!layout||!/^LIFE-\d{3}$/.test(catalogId))throw new Error('未知生活组合配方');
 const instances:Instance[]=layout.map(([n,x,y,z,q],i)=>{const assetId=typeof n==='string'?n:nativeLifeId(n),a=project.assets[assetId];if(!a)throw new Error('组合缺少母版 '+assetId);const position=[x,y,z].map(v=>Math.round(v/a.cellSize)*a.cellSize) as V3;return{id:id+'-'+i,assetId,name:a.name,position,rotation:q??0,parent:null};});
 return{id,name,version:1,instances};
}
